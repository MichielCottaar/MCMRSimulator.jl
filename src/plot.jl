"""
Defines a finite plane in the 3D space used for plotting.

# Constructor
    PlotPlane(normal=[0, 0, 1], position=[0, 0, 0]; size=10., sizex=<size>, sizey=<size>, ngrid=100)

Arguments:
- `normal`: length-3 vector with the orientation perpendicular to the plane (default to z-direction).
- `position`: position of plane as a length-3 vector (defaults to origin).
- `sizex`: size of the plane in the x-direction (before rotating to `normal`).
- `sizey`: size of the plane in the y-direction (before rotating to `normal`).
- `size`: set default value for `sizex` and `sizey`.
- `ngrid`: number of grid elements to split the plane up into for plotting.
"""
struct PlotPlane
    transformation :: CoordinateTransformations.Transformation
    sizex :: Real
    sizey :: Real
end


function PlotPlane(
    normal=:z, 
    position :: AbstractVector{<:Real}=zero(SVector{3, Float64});
    sizex=nothing, sizey=nothing, size=10.,
)
    if isnothing(sizex)
        sizex = size
    end
    if isnothing(sizey)
        sizey = size
    end
    rotation = get_rotation(normal, 3; reference_dimension=:z)
    position = SVector{3}(position)
    transform = CoordinateTransformations.AffineMap(rotation, position)
    PlotPlane(CoordinateTransformations.inv(transform), sizex, sizey)
end


function project(pp::PlotPlane, pos::SVector{3, Float64})
    base = pp.transformation(pos)
    sizex, sizey = pp.sizex, pp.sizey
    correct = [isfinite(sizex) ? sizex : 0., isfinite(sizey) ? sizey : 0., 0.] / 2.
    mod.(base .+ correct, (sizex, sizey, Inf)) .- correct
end

const ProjectedPoint = SVector{2, Float64}
const MeshPoint = SVector{3, Float64}

function project_mesh_plane(
    plot_plane::PlotPlane,
    mesh_data;
    atol=sqrt(eps(Float64)),
)
    projected = ProjectedPoint[]

    for mesh in mesh_data
        vertices = plot_plane.transformation.(mesh.vertices)
        for face in mesh.triangles
            triangle = ntuple(index -> vertices[face[index]], 3)
            _append_triangle_plane_intersection!(projected, triangle; atol)
        end
    end

    projected
end

function _append_triangle_plane_intersection!(
    projected,
    triangle::NTuple{3, MeshPoint};
    atol,
)
    tolerance = atol * max(1.0, maximum(norm, triangle))
    points = ProjectedPoint[]

    add_point!(point) = begin
        projected_point = ProjectedPoint(point[1], point[2])
        any(existing -> norm(existing - projected_point) <= tolerance, points) ||
            push!(points, projected_point)
    end

    for edge in ((1, 2), (2, 3), (3, 1))
        first = triangle[edge[1]]
        second = triangle[edge[2]]
        first_distance = first[3]
        second_distance = second[3]
        first_on_plane = abs(first_distance) <= tolerance
        second_on_plane = abs(second_distance) <= tolerance

        if first_on_plane && second_on_plane
            add_point!(first)
            add_point!(second)
        elseif first_on_plane
            add_point!(first)
        elseif second_on_plane
            add_point!(second)
        elseif signbit(first_distance) != signbit(second_distance)
            fraction = first_distance / (first_distance - second_distance)
            add_point!(first + fraction * (second - first))
        end
    end

    if length(points) == 2
        append!(projected, points)
        push!(projected, ProjectedPoint(NaN, NaN))
    elseif length(points) == 3
        for edge in ((1, 2), (2, 3), (3, 1))
            push!(projected, points[edge[1]])
            push!(projected, points[edge[2]])
            push!(projected, ProjectedPoint(NaN, NaN))
        end
    end
end

function project_trajectory(pp::PlotPlane, pos::AbstractVector{<:SVector{3, Float64}})
    transformed = pp.transformation.(pos)
    pos2D = map(p -> SVector{3, Float64}(
        isfinite(pp.sizex) ? p[1] / pp.sizex + 0.5 : 0.5,
        isfinite(pp.sizey) ? p[2] / pp.sizey + 0.5 : 0.5,
        0.5
    ), transformed)
    function to_pos!(time::Float64, position::SVector{3, Float64})
        idx1 = Int(floor(time))
        idx2 = Int(ceil(time))
        if idx1 == idx2
            pos_ref = pos2D[idx1]
        else
            pos_ref = pos2D[idx2] .* (time - idx1) .+ pos2D[idx1] .* (idx2 - time)
        end
        push!(all_pos, SVector{2}(
            isfinite(pp.sizex) ? pp.sizex * (position[1] - 0.5) : pos_ref[1],
            isfinite(pp.sizey) ? pp.sizey * (position[2] - 0.5) : pos_ref[2],
        ))
        push!(times, time)
    end
    empty = SVector{2, Float64}(NaN, NaN)
    all_pos = SVector{2, Float64}[]
    times = Float64[]
    for (pos_index, origin, destination) in zip(1:length(pos2D)-1, pos2D[1:end-1], pos2D[2:end])
        for (_, t1, p1, t2, p2) in  ray_grid_intersections(origin, destination)
            if pos_index == 1 && t1 == zero(t1)
                to_pos!(pos_index + t1, p1)
            end
            if t1 == zero(t1) && t2 == one(t2)
                to_pos!(pos_index + t2, p2)
            elseif t1 == zero(t1)
                to_pos!(pos_index + t2, p2)
                push!(all_pos, empty)
                push!(times, NaN)
            elseif t2 == one(t2)
                to_pos!(pos_index + t1, p1)
                to_pos!(pos_index + t2, p2)
            else
                to_pos!(pos_index + t1, p1)
                to_pos!(pos_index + t2, p2)
                push!(all_pos, empty)
                push!(times, NaN)
            end
        end
    end
    return all_pos, times
end


"""
    project_on_grid(plot_plane, snap, ngrid)

Spins from the [`Snapshot`](@ref) are projected onto the grid defined by [`PlotPlane`](@ref) in two ways:
- along the normal spins are projected onto the plane from infinitely far (TODO: give finite extent)
- in the other directions any spins are projected onto the plane using mod(position[1], `sizex`) and mod(position[2], `sizey`).
    This assumes that the geometry and field repeats itself ad infinitum beyond the `PlotPlane` (TODO: allow this assumption to be turned off).
In effect, this means that all spins are projected onto the `PlotPlane`. The average spin orientation in each grid cell is returned.
"""
function project_on_grid(pp::PlotPlane, snap::Snapshot{1}, ngrid::Int)
    positions = [project(pp, position(spin)) for spin in snap]
    xrange = extrema(v->v[1], positions)
    yrange = extrema(v->v[2], positions)

    res = zeros(MVector{3}, ngrid, ngrid)
    hits = zeros(Int, ngrid, ngrid)
    for (spin, pos) in zip(snap, positions)
        relx = (pos[1] - xrange[1])/(xrange[2] - xrange[1])
        rely = (pos[2] - yrange[1])/(yrange[2] - yrange[1])
        x_index = min.(Int(floor(relx * (ngrid - 1))), ngrid - 2) + 1
        y_index = min.(Int(floor(rely * (ngrid - 1))), ngrid - 2) + 1
        vs = orientation(spin)
        for (xi, yi) in [
            (x_index, y_index),
            (x_index+1, y_index),
            (x_index, y_index+1),
            (x_index+1, y_index+1),
        ]
            res[xi, yi] += vs
            hits[xi, yi] += 1
        end
    end
    (range(xrange..., ngrid), range(yrange..., ngrid), SpinOrientation.(res ./ hits))
end


function plot_bounding_box(plot_plane::PlotPlane)
    isfinite(plot_plane.sizex) && isfinite(plot_plane.sizey) ||
        throw(ArgumentError("2D geometry plotting requires finite plane dimensions"))

    inverse = CoordinateTransformations.inv(plot_plane.transformation)
    half_x = plot_plane.sizex / 2
    half_y = plot_plane.sizey / 2
    corners = [
        inverse(SVector{3, Float64}(x, y, 0.))
        for x in (-half_x, half_x), y in (-half_y, half_y)
    ]
    BoundingBox(
        [minimum(corner[dimension] for corner in corners) for dimension in 1:3],
        [maximum(corner[dimension] for corner in corners) for dimension in 1:3],
    )
end

function project_geometry(
    plot_plane::PlotPlane,
    geometry::GeometryLike;
    height=1.,
    nsamples=100,
)
    fixed_geometry = geometry isa FixedGeometry ? geometry : fix(geometry)
    mesh_data = geometry_mesh(
        fixed_geometry,
        plot_bounding_box(plot_plane);
        height,
        nsamples,
    )
    project_mesh_plane(plot_plane, mesh_data)
end


"""
    SingleSequenceDiagramLine(times, amplitudes, event_times, event_amplitudes)

A single line in a sequence diagram (e.g., RFx, Gy, ADC).
"""
struct SingleSequenceDiagramLine
    times :: Vector{Float64}
    amplitudes :: Vector{Float64}
    event_times :: Vector{Float64}
    event_amplitudes :: Vector{Float64}
end

duration_diagram(pl::SingleSequenceDiagramLine) = max(
    iszero(length(pl.times)) ? 0. : pl.times[end],
    iszero(length(pl.event_times)) ? 0. : pl.event_times[end],
)

SingleSequenceDiagramLine(times::Vector{Float64}, amplitudes::Vector{Float64}) = SingleSequenceDiagramLine(times, amplitudes, Float64[], Float64[])

function SingleSequenceDiagramLine(control_points::AbstractVector{<:Tuple}, duration::Number)
    times = [cp[1] for cp in control_points]
    amplitudes = [cp[2] for cp in control_points]
    if times[1] > 0
        pushfirst!(times, 0.)
        pushfirst!(amplitudes, 0.)
    end
    if times[end] < duration
        push!(times, duration)
        push!(amplitudes, 0.)
    end
    return SingleSequenceDiagramLine(times, amplitudes, Float64[], Float64[])
end

SingleSequenceDiagramLine(duration::Number) = SingleSequenceDiagramLine([0., duration], [0., 0.], Float64[], Float64[])

function normalise(lines::Vector{SingleSequenceDiagramLine})
    max_amp = maximum([maximum(abs.(line.amplitudes), init=0.) for line in lines])
    if iszero(max_amp)
        max_amp = 1.
    end

    max_event_amp = maximum([maximum(abs.(line.event_amplitudes), init=0.) for line in lines])
    if iszero(max_event_amp)
        max_event_amp = 1.
    end
    [SingleSequenceDiagramLine(line.times, line.amplitudes ./ max_amp, line.event_times, line.event_amplitudes ./ max_event_amp) for line in lines]
end

"""
    SequenceDiagram(; RFx, RFy, Gx, Gy, Gz, ADC)

All the lines forming a sequence diagram.

Each parameter should be a [`SinglePlotLine`](@ref) if provided.
Any parameters not provided will be set to a [`SinglePlotLine`](@ref) with zero amplitude.
"""
struct SequenceDiagram
    RFx :: SingleSequenceDiagramLine
    RFy :: SingleSequenceDiagramLine
    Gx :: SingleSequenceDiagramLine
    Gy :: SingleSequenceDiagramLine
    Gz :: SingleSequenceDiagramLine
    ADC :: SingleSequenceDiagramLine
end

function extend(sd::SingleSequenceDiagramLine, duration::Number)
    new_times = copy(sd.times)
    new_amplitudes = copy(sd.amplitudes)
    if length(sd.times) == 0 || sd.times[1] > 0
        pushfirst!(new_times, 0.)
        pushfirst!(new_amplitudes, 0.)
    end
    if new_times[end] < duration
        push!(new_times, duration)
        push!(new_amplitudes, 0.)
    end
    return SingleSequenceDiagramLine(new_times, new_amplitudes, sd.event_times, sd.event_amplitudes)
end

function extend(sd::SequenceDiagram)
    duration = duration_diagram(sd)
    SequenceDiagram(
        extend(sd.RFx, duration),
        extend(sd.RFy, duration),
        extend(sd.Gx, duration),
        extend(sd.Gy, duration),
        extend(sd.Gz, duration),
        extend(sd.ADC, duration),
    )
end

normalise(sd::SequenceDiagram) = SequenceDiagram(
    normalise([sd.RFx, sd.RFy])...,
    normalise([sd.Gx, sd.Gy, sd.Gz])...,
    normalise([sd.ADC])...,
)

function SequenceDiagram(waveform::SequenceWaveform)
    RF_times = Float64[]
    RF_ampl = ComplexF64[]

    for (start, finish, parts) in waveform.rf
        push!(RF_times, start)
        push!(RF_ampl, zero(ComplexF64))
        step_size = (finish - start) / length(parts)
        for (index, part) in enumerate(parts)
            push!(RF_times, start + (index - 0.5) * step_size)
            push!(RF_ampl, part.amplitude * exp(1im * deg2rad(part.phase)))
        end
    end

    instant_pulse_times = [t for (t, event) in waveform.instants if event isa PulseEvent]
    instant_pulse_amplitudes = [event.flip_angle * exp(1im * deg2rad(event.phase)) for (_, event) in waveform.instants if event isa PulseEvent]

    instant_grad_times = [t for (t, event) in waveform.instants if event isa GradientEvent]
    instant_grad_amplitudes = [
        [event.qvec[index] for (_, event) in waveform.instants if event isa GradientEvent]
        for index in 1:3
    ]
    SequenceDiagram(
        SingleSequenceDiagramLine(RF_times, real.(RF_ampl), instant_pulse_times, real.(instant_pulse_amplitudes)),
        SingleSequenceDiagramLine(RF_times, imag.(RF_ampl), instant_pulse_times, imag.(instant_pulse_amplitudes)),
        SingleSequenceDiagramLine(waveform.grads[1]..., instant_grad_times, instant_grad_amplitudes[1]),
        SingleSequenceDiagramLine(waveform.grads[2]..., instant_grad_times, instant_grad_amplitudes[2]),
        SingleSequenceDiagramLine(waveform.grads[3]..., instant_grad_times, instant_grad_amplitudes[3]),
        SingleSequenceDiagramLine(Float64[], Float64[], waveform.samples, [1. for _ in waveform.samples]),
    )
end

SequenceDiagram(diagram::SequenceDiagram) = diagram
SequenceDiagram(sequence) = SequenceDiagram(SequenceWaveform(sequence))

duration_diagram(sd::SequenceDiagram) = maximum([
    duration_diagram(sd.RFx),
    duration_diagram(sd.RFy),
    duration_diagram(sd.Gx),
    duration_diagram(sd.Gy),
    duration_diagram(sd.Gz),
    duration_diagram(sd.ADC),
])


